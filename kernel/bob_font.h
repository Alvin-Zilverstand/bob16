/* Draws uppercase 5x7 glyphs at cell-pixel resolution; clips at the right edge. */
int bob_gfx_bitmap_text(int x,int y,const char *text,int color) {
    int bitmap[560];
    int length=0,width,max_chars,character,glyph,cell;
    if(x<0||y<0||x>=80||y+7>25||color<0||color>15)return -1;
    max_chars=(80-x+1)/6;
    while(text[length]&&length<max_chars)length++;
    if(!length)return 0;
    width=length*6-1;
    for(int i=0;i<width*7;i++)bitmap[i]=0;
    for(int i=0;i<length;i++) {
        character=text[i];
        if(character>='a'&&character<='z')character-=32;
        if(character==' ')glyph=0;
        else if(character>='A'&&character<='Z')glyph=1+character-'A';
        else if(character>='0'&&character<='9')glyph=27+character-'0';
        else if(character=='!')glyph=38;
        else if(character=='-')glyph=39;
        else if(character=='.')glyph=40;
        else glyph=37;
        for(int column=0;column<5;column++)for(int row=0;row<7;row++) {
            cell=(bob_font5x7[glyph][column]&(1<<row))?('#'|(color<<8)):0;
            bitmap[row*width+i*6+column]=cell;
        }
    }
    return bob_gfx_blit_color(x,y,width,7,bitmap);
}

